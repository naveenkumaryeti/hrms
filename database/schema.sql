CREATE DATABASE IF NOT EXISTS hrms_db CHARACTER SET utf8mb4;
USE hrms_db;
CREATE TABLE IF NOT EXISTS roles (
  role_name VARCHAR(20) PRIMARY KEY,
  description VARCHAR(100)
) ENGINE=InnoDB;
INSERT IGNORE INTO roles VALUES ('ADMIN','Full HR access'),('EMPLOYEE','View own profile only');
CREATE TABLE IF NOT EXISTS employees (
  employee_id INT AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(100) NOT NULL,
  email VARCHAR(120) NOT NULL UNIQUE,
  department VARCHAR(50) NOT NULL,
  designation VARCHAR(50) NOT NULL,
  joining_date DATE NOT NULL,
  employment_status ENUM('ACTIVE','ON_LEAVE','RESIGNED') NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB AUTO_INCREMENT=1001;
CREATE TABLE IF NOT EXISTS users (
  user_id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(30) NOT NULL UNIQUE,
  email VARCHAR(120) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'EMPLOYEE',
  employee_id INT NULL UNIQUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_users_role FOREIGN KEY (role) REFERENCES roles(role_name),
  CONSTRAINT fk_users_employee FOREIGN KEY (employee_id) REFERENCES employees(employee_id) ON DELETE SET NULL
) ENGINE=InnoDB;
